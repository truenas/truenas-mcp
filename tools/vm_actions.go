func planStopVM(ctx context.Context, client *truenas.Client, args map[string]interface{}) (*writePlan, error) {
	vm, err := lookupVMWithStatus(ctx, client, args)
	if err != nil {
		return nil, err
	}
	force, _ := args["force"].(bool)
	forceAfterTimeout, _ := args["force_after_timeout"].(bool)

	var blocked, warnings []string
	if vm.State == "STOPPED" {
		blocked = append(blocked, fmt.Sprintf("cannot stop VM %q (id %d): it is already STOPPED; nothing was executed", vm.Name, vm.ID))
	}
	if force {
		warnings = append(warnings, "force=true terminates the VM immediately without waiting for graceful guest shutdown; unsaved guest data may be lost")
	} else if forceAfterTimeout {
		warnings = append(warnings, "force_after_timeout=true will forcibly power off the VM if the guest does not shut down within its shutdown_timeout")
	}

	opts := map[string]interface{}{
		"force":               force,
		"force_after_timeout": forceAfterTimeout,
	}
	mode := "graceful ACPI shutdown"
	if force {
		mode = "forced stop"
	} else if forceAfterTimeout {
		mode = "graceful shutdown with force after timeout"
	}
	headline := fmt.Sprintf("Stop VM %q (id %d) (%s)", vm.Name, vm.ID, mode)

	return &writePlan{
		Tool:          "stop_vm",
		Method:        vmStopMethod,
		CallParams:    []interface{}{vm.ID, opts},
		ParamNames:    []string{"id", "options"},
		JobMethod:     vmStopMethod,
		Description:   headline,
		Operation:     "stop",
		CurrentState:  vm.currentState(),
		Warnings:      warnings,
		Blocked:       blocked,
		EstimatedTime: &EstimatedTime{MinSeconds: 5, MaxSeconds: 120, Note: "Depends on guest OS shutdown time"},
		TargetName:    vm.Name,
		Bind: map[string]interface{}{
			"vm_id":               vm.ID,
			"vm_name":             vm.Name,
			"vm_uuid":             vm.UUID,
			"status":              vm.statusBind(),
			"force":               force,
			"force_after_timeout": forceAfterTimeout,
		},
		ConfirmSummary: newConfirmSummary(
			headline,
			confirmFact("VM", fmt.Sprintf("%s (id %d)", vm.Name, vm.ID)),
			confirmFact("current state", vm.State),
			confirmFact("mode", mode),
			confirmBoolFact("force", force),
			confirmBoolFact("force_after_timeout", forceAfterTimeout),
		),
		Result: map[string]interface{}{"vm": vm},
	}, nil
}

