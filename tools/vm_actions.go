func lookupVMWithStatus(ctx context.Context, client *truenas.Client, args map[string]interface{}) (*resolvedVM, error) {
	vmID, hasID, err := vmIntArg(args, "id", 0)
	if err != nil || (hasID && vmID < 1) {
		return nil, fmt.Errorf("id must be a positive integer")
	}
	name, hasName := args["name"].(string)
	if !hasID && (!hasName || name == "") {
		return nil, fmt.Errorf("provide id or name to select a VM")
	}
	if hasName && name != "" && hasLineBreak(name) {
		return nil, fmt.Errorf("name must be a single line")
	}

	var filters []interface{}
	if hasID {
		filters = []interface{}{[]interface{}{"id", "=", vmID}}
	} else {
		filters = []interface{}{[]interface{}{"name", "=", name}}
	}
	raw, err := client.Call(ctx, "vm.query", filters, map[string]interface{}{"select": vmQuerySelect})
	if err != nil {
		return nil, fmt.Errorf("failed to query VM: %w", err)
	}
	var rows []map[string]interface{}
	if err := json.Unmarshal(raw, &rows); err != nil {
		return nil, fmt.Errorf("failed to parse vm.query response: %w", err)
	}

	var matched map[string]interface{}
	for _, row := range rows {
		idFloat, _ := row["id"].(float64)
		rowName, _ := row["name"].(string)
		if hasID && int(idFloat) != vmID {
			continue
		}
		if hasName && name != "" && rowName != name {
			if hasID {
				return nil, fmt.Errorf("VM id %d has name %q, which does not match requested name %q", vmID, rowName, name)
			}
			continue
		}
		matched = row
		break
	}
	if matched == nil {
		if hasID {
			return nil, fmt.Errorf("VM with id %d not found", vmID)
		}
		return nil, fmt.Errorf("VM %q not found", name)
	}

	idFloat, ok := matched["id"].(float64)
	if !ok || idFloat < 1 || math.Trunc(idFloat) != idFloat {
		return nil, fmt.Errorf("vm.query returned a VM with an invalid id")
	}
	resolvedID := int(idFloat)
	resolvedName, _ := matched["name"].(string)
	resolvedUUID, _ := matched["uuid"].(string)
	memFloat, _ := matched["memory"].(float64)
	autostart, _ := matched["autostart"].(bool)

	statusRaw, err := client.Call(ctx, "vm.status", resolvedID)
	if err != nil {
		return nil, fmt.Errorf("failed to query live status for VM %q (id %d): %w", resolvedName, resolvedID, err)
	}
	var statusObj map[string]interface{}
	if err := json.Unmarshal(statusRaw, &statusObj); err != nil {
		return nil, fmt.Errorf("failed to parse vm.status for VM %q (id %d): %w", resolvedName, resolvedID, err)
	}
	state, _ := statusObj["state"].(string)
	if state == "" {
		return nil, fmt.Errorf("vm.status for VM %q (id %d) did not report a state", resolvedName, resolvedID)
	}

	return &resolvedVM{
		ID:          resolvedID,
		Name:        resolvedName,
		UUID:        resolvedUUID,
		MemoryMiB:   int(memFloat),
		Autostart:   autostart,
		State:       strings.ToUpper(state),
		PID:         statusObj["pid"],
		DomainState: statusObj["domain_state"],
		Raw:         matched,
	}, nil
}

func planStartVM(ctx context.Context, client *truenas.Client, args map[string]interface{}) (*writePlan, error) {
	vm, err := lookupVMWithStatus(ctx, client, args)
	if err != nil {
		return nil, err
	}
	overcommit, _ := args["overcommit"].(bool)

	var blocked, warnings []string
	if vm.State == "RUNNING" || vm.State == "SUSPENDED" {
		blocked = append(blocked, fmt.Sprintf("cannot start VM %q (id %d): it is already %s; nothing was executed", vm.Name, vm.ID, vm.State))
	}

	virtSupported, virtErr, err := checkVirtualizationSupported(ctx, client)
	if err != nil {
		return nil, err
	}
	if !virtSupported {
		msg := "host does not support virtualization"
		if virtErr != "" {
			msg = fmt.Sprintf("%s: %s", msg, virtErr)
		}
		blocked = append(blocked, msg)
	}

	availMemBytes, err := fetchAvailableVMMemory(ctx, client, overcommit)
	if err != nil {
		return nil, err
	}
	vmMemBytes := int64(vm.MemoryMiB) * 1024 * 1024
	if vmMemBytes > 0 && vmMemBytes > availMemBytes {
		blocked = append(blocked, fmt.Sprintf("cannot start VM %q (id %d): requires %d MiB (%s) but only %s is available (overcommit=%t)",
			vm.Name, vm.ID, vm.MemoryMiB, formatBytes(vmMemBytes), formatBytes(availMemBytes), overcommit))
	}
	if overcommit {
		warnings = append(warnings, "overcommit=true allows starting the VM even when unconsumed memory of other VMs would exceed available RAM")
	}

	opts := map[string]interface{}{"overcommit": overcommit}
	current := vm.currentState()
	current["available_memory_bytes"] = availMemBytes

	headline := fmt.Sprintf("Start VM %q (id %d)", vm.Name, vm.ID)
	return &writePlan{
		Tool:         "start_vm",
		Method:       vmStartMethod,
		CallParams:   []interface{}{vm.ID, opts},
		ParamNames:   []string{"id", "options"},
		Description:  headline,
		Operation:    "start",
		CurrentState: current,
		Warnings:     warnings,
		Blocked:      blocked,
		TargetName:   vm.Name,
		Bind: map[string]interface{}{
			"vm_id":      vm.ID,
			"vm_name":    vm.Name,
			"vm_uuid":    vm.UUID,
			"status":     vm.statusBind(),
			"memory_mib": vm.MemoryMiB,
			"overcommit": overcommit,
		},
		ConfirmSummary: newConfirmSummary(
			headline,
			confirmFact("VM", fmt.Sprintf("%s (id %d)", vm.Name, vm.ID)),
			confirmFact("current state", vm.State),
			confirmFact("memory", fmt.Sprintf("%d MiB", vm.MemoryMiB)),
			confirmBoolFact("overcommit", overcommit),
		),
		Result: map[string]interface{}{"vm": vm},
	}, nil
}

