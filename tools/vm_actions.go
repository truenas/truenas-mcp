// handlePlanned runs the shared plan, refuses a blocked plan, returns the
// preview for dry_run and otherwise executes the plan.
func handlePlanned(
	ctx context.Context, client *truenas.Client, args map[string]interface{},
	plan func(context.Context, *truenas.Client, map[string]interface{}) (*writePlan, error),
	execute func(context.Context, *truenas.Client, map[string]interface{}, *writePlan) (string, error),
) (string, error) {
	p, err := plan(ctx, client, args)
	if err != nil {
		return "", err
	}
	if err := p.blockedReply(); err != nil {
		return "", err
	}
	if dryRun, ok := args["dry_run"].(bool); ok && dryRun {
		return p.marshalDryRun()
	}
	return execute(ctx, client, args, p)
}

func (r *Registry) executeCreateVM(ctx context.Context, client *truenas.Client, _ map[string]interface{}, plan *writePlan) (string, error) {
	if err := plan.blockedReply(); err != nil {
		return "", err
	}
	vmRaw, err := callPlan(ctx, client, plan)
	if err != nil {
		return "", fmt.Errorf("failed to create VM %q: %w", plan.TargetName, err)
	}
	var createdVM map[string]interface{}
	if err := json.Unmarshal(vmRaw, &createdVM); err != nil {
		return "", fmt.Errorf("failed to parse created VM response: %w", err)
	}
	vmIDFloat, ok := createdVM["id"].(float64)
	if !ok || vmIDFloat < 1 || math.Trunc(vmIDFloat) != vmIDFloat {
		return "", fmt.Errorf("vm.create returned an invalid VM id")
	}
	vmID := int(vmIDFloat)

	plannedDevices, _ := plan.Result["devices"].([]plannedVMDevice)
	createdDevices := make([]map[string]interface{}, 0, len(plannedDevices))
	var createdZvols []string
	for i, pd := range plannedDevices {
		payload := map[string]interface{}{
			"vm":         vmID,
			"attributes": pd.Attributes,
		}
		if pd.HasOrder {
			payload["order"] = pd.Order
		}
		devRaw, err := client.Call(ctx, "vm.device.create", payload)
		if err != nil {
			return "", rollbackCreateVM(ctx, client, plan.TargetName, vmID, i, pd, len(createdDevices), len(plannedDevices), createdZvols, err)
		}
		if zv := plannedZvol(pd); zv != "" {
			createdZvols = append(createdZvols, zv)
		}
		var devObj map[string]interface{}
		if err := json.Unmarshal(devRaw, &devObj); err != nil {
			createdDevices = append(createdDevices, map[string]interface{}{"dtype": pd.DType, "attributes": pd.Preview})
			continue
		}
		createdDevices = append(createdDevices, sanitizeCreatedDevice(devObj))
	}

	summary := simplifyVM(createdVM)
	resp := map[string]interface{}{
		"vm":           summary,
		"devices":      createdDevices,
		"device_count": len(createdDevices),
	}
	msg := fmt.Sprintf("Created VM %q (id %d) with %d device(s). Use start_vm to power it on.", plan.TargetName, vmID, len(createdDevices))
	if autostart, _ := plan.Result["autostart"].(bool); autostart {
		if _, err := client.Call(ctx, "vm.update", vmID, map[string]interface{}{"autostart": true}); err != nil {
			return "", fmt.Errorf("created VM %q (id %d) with all %d device(s), but enabling autostart with vm.update failed, so autostart is still off: %w",
				plan.TargetName, vmID, len(createdDevices), err)
		}
		summary["autostart"] = true
		msg = fmt.Sprintf("Created VM %q (id %d) with %d device(s) and enabled autostart. Use start_vm to power it on.", plan.TargetName, vmID, len(createdDevices))
	}
	resp["message"] = msg
	return marshalJSON(resp)
}

// plannedZvol returns the zvol a DISK device creates, or "".
func plannedZvol(pd plannedVMDevice) string {
	if pd.DType != "DISK" {
		return ""
	}
	if create, _ := pd.Attributes["create_zvol"].(bool); !create {
		return ""
	}
	name, _ := pd.Attributes["zvol_name"].(string)
	return name
}

// rollbackCreateVM deletes a VM whose device attach failed. The VM was
// created with autostart off, and vm.delete is called with zvols=false, so
// zvols this call created are kept and listed for the operator.
func rollbackCreateVM(ctx context.Context, client *truenas.Client, name string, vmID, failedIdx int, failed plannedVMDevice, attached, total int, createdZvols []string, attachErr error) error {
	zvols := "none"
	if len(createdZvols) > 0 {
		zvols = strings.Join(createdZvols, ", ")
	}
	maybe := ""
	if zv := plannedZvol(failed); zv != "" {
		maybe = fmt.Sprintf("; zvol %s of the failed device may also have been created", zv)
	}
	attachMsg := fmt.Sprintf("attached %d of %d device(s) to new VM %q (id %d), then failed to attach devices[%d] (%s): %v",
		attached, total, name, vmID, failedIdx, failed.DType, attachErr)
	if _, err := client.Call(ctx, "vm.delete", vmID, map[string]interface{}{"zvols": false, "force": false}); err != nil {
		return fmt.Errorf("%s. Rollback with vm.delete also failed (%v): VM %q (id %d) still exists with autostart off and %d device(s) attached. Zvols created by this call: %s%s",
			attachMsg, err, name, vmID, attached, zvols, maybe)
	}
	return fmt.Errorf("%s. Rolled back: deleted VM %q (id %d) with vm.delete (zvols kept). Zvols created by this call and kept: %s%s",
		attachMsg, name, vmID, zvols, maybe)
}

