func validateMACAddress(mac string) error {
	if !vmMACRegex.MatchString(mac) {
		return fmt.Errorf("invalid MAC address %q (expected xx:xx:xx:xx:xx:xx)", mac)
	}
	firstOctet, err := strconv.ParseUint(mac[:2], 16, 8)
	if err != nil {
		return fmt.Errorf("invalid MAC address %q", mac)
	}
	if firstOctet&1 != 0 {
		return fmt.Errorf("MAC address %q is multicast or broadcast (first octet must be unicast)", mac)
	}
	return nil
}

