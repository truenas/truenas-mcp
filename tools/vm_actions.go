func planResetVM(ctx context.Context, client *truenas.Client, args map[string]interface{}) (*writePlan, error) {
	vm, err := lookupVMWithStatus(ctx, client, args)
	if err != nil {
		return nil, err
	}
	var blocked []string
	if vm.State != "RUNNING" {
		blocked = append(blocked, fmt.Sprintf("cannot reset VM %q (id %d): it is currently %s (must be RUNNING); nothing was executed", vm.Name, vm.ID, vm.State))
	}
	headline := fmt.Sprintf("Forcibly hardware-reset VM %q (id %d)", vm.Name, vm.ID)
	return &writePlan{
		Tool:         "reset_vm",
		Method:       vmResetMethod,
		CallParams:   []interface{}{vm.ID},
		ParamNames:   []string{"id"},
		Description:  headline,
		Operation:    "reset",
		CurrentState: vm.currentState(),
		Warnings: []string{
			"Forced hardware reset reboots the VM immediately without guest OS shutdown; unsaved guest data and filesystems may be damaged. Use restart_vm for a graceful restart.",
		},
		Blocked:    blocked,
		TargetName: vm.Name,
		Bind: map[string]interface{}{
			"vm_id":   vm.ID,
			"vm_name": vm.Name,
			"vm_uuid": vm.UUID,
			"status":  vm.statusBind(),
		},
		ConfirmSummary: newConfirmSummary(
			headline,
			confirmFact("VM", fmt.Sprintf("%s (id %d)", vm.Name, vm.ID)),
			confirmFact("current state", vm.State),
			confirmFact("effect", "immediate forced hardware reset (no guest shutdown)"),
		),
		Result: map[string]interface{}{"vm": vm},
	}, nil
}

func (r *Registry) handleResetVM(ctx context.Context, client *truenas.Client, args map[string]interface{}) (string, error) {
	return handlePlanned(ctx, client, args, planResetVM, r.executeResetVM)
}

func (r *Registry) executeResetVM(ctx context.Context, client *truenas.Client, _ map[string]interface{}, plan *writePlan) (string, error) {
	return executeVMPowerCall(ctx, client, plan, "reset", "reset", "Forcibly reset")
}

// executeVMPowerCall runs a non-job power plan (vm.start, vm.poweroff,
// vm.reset) and reports the result.
func executeVMPowerCall(ctx context.Context, client *truenas.Client, plan *writePlan, verb, status, done string) (string, error) {
	if err := plan.blockedReply(); err != nil {
		return "", err
	}
	if _, err := callPlan(ctx, client, plan); err != nil {
		return "", fmt.Errorf("failed to %s VM %q: %w", verb, plan.TargetName, err)
	}
	vm, _ := plan.Result["vm"].(*resolvedVM)
	resp := map[string]interface{}{
		"vm_id":   vm.ID,
		"name":    vm.Name,
		"status":  status,
		"message": fmt.Sprintf("%s VM %q (id %d). Use query_vms to verify its status.", done, vm.Name, vm.ID),
	}
	return marshalJSON(resp)
}

// executeVMPowerJob runs a job power plan (vm.stop, vm.restart) and tracks
// the middleware job as a task.
func (r *Registry) executeVMPowerJob(ctx context.Context, client *truenas.Client, args map[string]interface{}, plan *writePlan, tool, verb string) (string, error) {
	if err := plan.blockedReply(); err != nil {
		return "", err
	}
	raw, err := callPlan(ctx, client, plan)
	if err != nil {
		return "", fmt.Errorf("failed to %s VM %q: %w", verb, plan.TargetName, err)
	}
	jobID, err := parseJobID(raw)
	if err != nil {
		return "", fmt.Errorf("failed to parse %s job ID: %w", plan.Method, err)
	}
	opts := []tasks.TaskOption{}
	if plan.JobMethod != "" {
		opts = append(opts, tasks.WithExpectedMethod(plan.JobMethod))
	}
	task, err := r.taskManager.CreateJobTask(ctx, tool, args, jobID, vmJobTTL, opts...)
	if err != nil {
		return "", fmt.Errorf("failed to create task for %s: %w", tool, err)
	}
	vm, _ := plan.Result["vm"].(*resolvedVM)
	resp := map[string]interface{}{
		"vm_id":         vm.ID,
		"name":          vm.Name,
		"task_id":       task.TaskID,
		"task_status":   task.Status,
		"poll_interval": task.PollInterval,
		"job_id":        jobID,
		"message":       fmt.Sprintf("VM %s initiated for %q (id %d). Track progress with tasks_get using task_id: %s", verb, vm.Name, vm.ID, task.TaskID),
	}
	return marshalJSON(resp)
}
