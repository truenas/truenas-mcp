func vmIntArg(m map[string]interface{}, key string, def int) (int, bool, error) {
	v, ok := m[key]
	if !ok || v == nil {
		return def, false, nil
	}
	f, ok := jsonNumber(v)
	if !ok || math.Trunc(f) != f || math.IsNaN(f) || math.IsInf(f, 0) {
		return 0, true, fmt.Errorf("%s must be an integer", key)
	}
	return int(f), true, nil
}

func vmInt64Arg(m map[string]interface{}, key string) (int64, bool, error) {
	v, ok := m[key]
	if !ok || v == nil {
		return 0, false, nil
	}
	switch n := v.(type) {
	case int:
		return int64(n), true, nil
	case int64:
		return n, true, nil
	case float64:
		if math.Trunc(n) != n || math.IsNaN(n) || math.IsInf(n, 0) || n > float64(math.MaxInt64) || n < float64(math.MinInt64) {
			return 0, true, fmt.Errorf("%s must be an integer", key)
		}
		return int64(n), true, nil
	default:
		return 0, true, fmt.Errorf("%s must be an integer", key)
	}
}

func hasLineBreak(s string) bool {
	return strings.ContainsAny(s, "\r\n")
}

func vmSecretHash(s string) string {
	sum := sha256.Sum256([]byte(s))
	return hex.EncodeToString(sum[:])
}

func extractZFSBool(v interface{}) (bool, bool) {
	switch x := v.(type) {
	case bool:
		return x, true
	case string:
		switch strings.ToLower(x) {
		case "on", "true", "yes":
			return true, true
		case "off", "false", "no":
			return false, true
		}
	case map[string]interface{}:
		if p, ok := x["parsed"]; ok {
			return extractZFSBool(p)
		}
		if raw, ok := x["value"]; ok {
			return extractZFSBool(raw)
		}
	}
	return false, false
}

func extractZFSInt64(v interface{}) (int64, bool) {
	switch x := v.(type) {
	case int:
		return int64(x), true
	case int64:
		return x, true
	case float64:
		if !math.IsNaN(x) && !math.IsInf(x, 0) {
			return int64(x), true
		}
	case map[string]interface{}:
		if p, ok := x["parsed"]; ok {
			return extractZFSInt64(p)
		}
	}
	return 0, false
}

type vmNicAttachChoices struct {
	Bridges  []string
	Macvlans []string
	bridge   map[string]bool
	macvlan  map[string]bool
}

func (c *vmNicAttachChoices) lookup(name string) (mode string, ok bool) {
	if c == nil {
		return "", false
	}
	if c.bridge[name] {
		return "bridge", true
	}
	if c.macvlan[name] {
		return "macvtap", true
	}
	return "", false
}

func (c *vmNicAttachChoices) bind() map[string]interface{} {
	if c == nil {
		return nil
	}
	return map[string]interface{}{
		"bridges":  c.Bridges,
		"macvlans": c.Macvlans,
	}
}

func fetchVMNicAttachChoices(ctx context.Context, client *truenas.Client) (*vmNicAttachChoices, error) {
	raw, err := client.Call(ctx, "vm.device.nic_attach_choices")
	if err != nil {
		return nil, fmt.Errorf("failed to query vm.device.nic_attach_choices: %w", err)
	}
	var obj map[string]interface{}
	if err := json.Unmarshal(raw, &obj); err != nil {
		return nil, fmt.Errorf("failed to parse vm.device.nic_attach_choices: %w", err)
	}
	out := &vmNicAttachChoices{
		Bridges:  []string{},
		Macvlans: []string{},
		bridge:   map[string]bool{},
		macvlan:  map[string]bool{},
	}
	// TrueNAS 27.0+/master returns {"BRIDGE": [...], "MACVLAN": [...]}.
	// TrueNAS 25.10 returns {"br0": "br0", "eno1": "eno1"}.
	_, hasBridgeList := obj["BRIDGE"].([]interface{})
	_, hasMacvlanList := obj["MACVLAN"].([]interface{})
	if hasBridgeList || hasMacvlanList {
		if list, ok := obj["BRIDGE"].([]interface{}); ok {
			for _, item := range list {
				if name, ok := item.(string); ok && name != "" && !out.bridge[name] {
					out.bridge[name] = true
					out.Bridges = append(out.Bridges, name)
				}
			}
		}
		if list, ok := obj["MACVLAN"].([]interface{}); ok {
			for _, item := range list {
				if name, ok := item.(string); ok && name != "" && !out.macvlan[name] && !out.bridge[name] {
					out.macvlan[name] = true
					out.Macvlans = append(out.Macvlans, name)
				}
			}
		}
	} else {
		for name, val := range obj {
			if _, ok := val.(string); !ok || name == "" {
				continue
			}
			if strings.HasPrefix(name, "br") {
				out.bridge[name] = true
				out.Bridges = append(out.Bridges, name)
			} else {
				out.macvlan[name] = true
				out.Macvlans = append(out.Macvlans, name)
			}
		}
	}
	sort.Strings(out.Bridges)
	sort.Strings(out.Macvlans)
	return out, nil
}

